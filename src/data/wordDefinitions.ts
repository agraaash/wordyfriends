export function getWordMetadata(word: string): WordMetadata {
  const cleanWord = word.trim().toLowerCase();
  if (WORD_METADATA_DICT[cleanWord]) {
    return WORD_METADATA_DICT[cleanWord];
  }

  // Fallback generator for any custom word
  const capitalized = word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
  return {
    word: cleanWord,
    definition: `Describing the state, feeling, or quality of being ${cleanWord}.`,
    simpleExplanation: `Feeling or acting in a ${cleanWord} way.`,
    example: `She felt very ${cleanWord} during the exciting adventure.`,
    partOfSpeech: 'adjective',
    phonetic: `[${capitalized.toUpperCase()}]`,
    emoji: '✨',
  };
}
